def render_all():
    return {
        'architecture.svg': architecture(),
        'model-lifecycle.svg': lifecycle(),
        'memory-and-sharing.svg': memory(),
    }


def check(directory=OUTPUT):
    errors = []
    for name, expected in render_all().items():
        path = directory / name
        if not path.is_file() or path.read_text(encoding='utf-8') != expected:
            errors.append(f'Diagram missing or stale: {name}; run python tools/docs_diagrams.py')
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check without rewriting files.')
    args = parser.parse_args()
    if args.check:
        errors = check()
        print('\n'.join(errors) if errors else 'All handbook diagrams match their sources.')
        return 1 if errors else 0
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for name, content in render_all().items():
        (OUTPUT / name).write_text(content, encoding='utf-8')
        print(f'Rendered {name}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
