"""Render the handbook's reviewed diagrams as deterministic, self-contained SVGs.

The drawing functions below are the editable sources. No browser, network,
third-party renderer, fonts or JavaScript is needed to generate or read them.
"""
import argparse
from html import escape
from pathlib import Path


OUTPUT = Path(__file__).resolve().parents[1] / 'docs/assets/diagrams'
COLORS = {
    'background': '#080f1b', 'surface': '#0e1b2b', 'border': '#29405a',
    'text': '#e6edf8', 'muted': '#b8c8db', 'cyan': '#35cfe6',
    'purple': '#a58bfa', 'green': '#55d8ae', 'amber': '#f5c95c',
}


class Diagram:
    """Small SVG vocabulary; all prose and layout stay explicit and reviewable."""

    def __init__(self, name, height, title, description, subtitle):
        self.name = name
        self.parts = [
            '<?xml version="1.0" encoding="UTF-8"?>',
            '<!-- SPDX-License-Identifier: BUSL-1.1 -->',
            '<!-- Generated by tools/docs_diagrams.py. Edit that source, not this SVG. -->',
            f'<svg xmlns="http://www.w3.org/2000/svg" width="640" height="{height}" '
            f'viewBox="0 0 640 {height}" role="img" '
            f'aria-labelledby="{name}-title {name}-desc">',
            f'<title id="{name}-title">{escape(title)}</title>',
            f'<desc id="{name}-desc">{escape(description)}</desc>',
            '<defs>',
        ]
        for color in ('cyan', 'purple', 'muted', 'amber'):
            self.parts.append(
                f'<marker id="arrow-{color}" viewBox="0 0 10 10" refX="9" refY="5" '
                f'markerWidth="8" markerHeight="8" orient="auto-start-reverse">'
                f'<path d="M 1 1 L 9 5 L 1 9" fill="none" stroke="{COLORS[color]}" '
                'stroke-width="1.5" stroke-linejoin="round"/></marker>')
        self.parts += ['</defs>',
                       '<g font-family="system-ui, -apple-system, Segoe UI, Arial, sans-serif">']
        self.rect(0, 0, 640, height, 'background', radius=16, border=False)
        self.text(32, 52, title, size=30, weight=650)
        self.text(32, 88, subtitle, color='muted', size=22)

    def rect(self, x, y, width, height, fill='surface', radius=12,
             border=True, dashed=False, stroke='border'):
        self.parts.append(
            f'<rect x="{x}" y="{y}" width="{width}" height="{height}" rx="{radius}" '
            f'fill="{COLORS[fill]}" stroke="{COLORS[stroke] if border else "none"}" '
            f'stroke-width="1.5"' + (' stroke-dasharray="7 6"' if dashed else '') + '/>')

    def text(self, x, y, lines, size=22, color='text', weight=400, anchor='start', gap=30):
        if isinstance(lines, str):
            lines = [lines]
        self.parts.append(f'<text x="{x}" y="{y}" fill="{COLORS[color]}" '
                          f'font-size="{size}" font-weight="{weight}" text-anchor="{anchor}">')
        for index, line in enumerate(lines):
            self.parts.append(f'<tspan x="{x}" dy="{0 if index == 0 else gap}">{escape(line)}</tspan>')
        self.parts.append('</text>')

    def arrow(self, points, color='cyan', dashed=False):
        path = 'M ' + ' L '.join(f'{x} {y}' for x, y in points)
        self.parts.append(f'<path d="{path}" fill="none" stroke="{COLORS[color]}" '
                          'stroke-width="2" stroke-linejoin="round" '
                          f'marker-end="url(#arrow-{color})"' +
                          (' stroke-dasharray="7 6"' if dashed else '') + '/>')

    def result(self):
        return '\n'.join([*self.parts, '</g>', '</svg>', ''])


