def nav_paths(value):
    if isinstance(value, str): yield value
    elif isinstance(value, list):
        for item in value: yield from nav_paths(item)
    elif isinstance(value, dict):
        for item in value.values(): yield from nav_paths(item)


def check():
    errors = check_links(source_files(), ROOT)
    errors += docs_diagrams.check(DOCS / 'assets/diagrams')
    expected = compatibility()
    path = DOCS / 'reference/compatibility.md'
    if not path.exists() or path.read_text() != expected:
        errors.append('Compatibility reference is stale: run python tools/docs.py inventory')
    nav = list(nav_paths(json.loads((DOCS / 'navigation.json').read_text())))
    if len(nav) != len(set(nav)): errors.append('Navigation contains duplicate pages')
    for value in nav:
        if not (DOCS / value).is_file(): errors.append(f'Navigation target missing: {value}')
    for section in ['get-started', 'installation', 'user-guide', 'administration', 'concepts', 'reference', 'development']:
        for page in (DOCS / section).rglob('*.md'):
            key = page.relative_to(DOCS).as_posix()
            migration = json.loads((DOCS / 'migration.json').read_text())
            if key in migration and migration[key]['target'] != key: continue
            if key not in nav: errors.append(f'Canonical page is not navigable: {key}')
    for old, record in json.loads((DOCS / 'migration.json').read_text()).items():
        source = DOCS / old
        if not source.exists():
            errors.append(f'Legacy Markdown path missing: {old}')
            continue
        old_ids = parse(source).ids
        for anchor, destination in record['anchors'].items():
            if anchor not in old_ids: errors.append(f'Legacy anchor lost: {old}#{anchor}')
            target, _, fragment = destination.partition('#')
            p = DOCS / target
            if not p.exists(): errors.append(f'Migration target missing: {destination}')
            elif fragment and fragment not in parse(p).ids:
                errors.append(f'Migration target anchor missing: {destination}')
    if errors:
        print('\n'.join(sorted(set(errors))))
        return False
    print(f'Documentation checks passed: {len(nav)} navigation entries; source links, legacy anchors and catalog reference.')
    return True


def page_url(path):
    p = Path(path)
    return ('handbook/' + (p.parent.as_posix() + '/' if p.parent.as_posix() != '.' else '')) if p.name in ('README.md', 'index.md') else 'handbook/' + p.with_suffix('').as_posix() + '/'


def redirect_document(default, anchors):
    # All targets come from the checked local migration map, never request input.
    payload = json.dumps({'default':default, 'anchors':anchors}).replace('<', '\\u003c')
    return ('<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width">'
            '<title>Documentation moved · Magic Stick</title><p>This page has moved. '
            f'<a href="{html.escape(default, quote=True)}">Open the current guide</a>.</p>'
            '<script>const routes=' + payload + ';let key=location.hash.slice(1);'
            'try{key=decodeURIComponent(key)}catch{}location.replace(routes.anchors[key]||routes.default);</script></html>')


def marketing_links(text):
    """Resolve canonical Markdown links in the landing page at build time."""
    def replace(match):
        href = match[2]
        url = urlsplit(href)
        if url.scheme or url.netloc or not url.path.endswith('.md'):
            return match[0]
        route = page_url(url.path)
        return match[1] + route + ('#' + url.fragment if url.fragment else '') + match[3]
    return re.sub(r'(href=")([^"]+)(")', replace, text)


def check_migration_output():
    errors, cache = [], {}
    for old, record in json.loads((DOCS / 'migration.json').read_text()).items():
        for route in [record['target'], *record['anchors'].values()]:
            path, _, fragment = route.partition('#')
            target = OUT / page_url(path) / 'index.html'
            if not target.is_file():
                errors.append(f'Legacy route {old}: missing rendered target {route}')
            elif fragment:
                if target not in cache: cache[target] = parse(target).ids
                if fragment not in cache[target]:
                    errors.append(f'Legacy route {old}: missing rendered anchor {route}')
    return sorted(set(errors))


def build():
    if not check(): return False
    if OUT.exists(): shutil.rmtree(OUT)
    OUT.mkdir(parents=True, exist_ok=True)
    subprocess.run([sys.executable, '-m', 'mkdocs', 'build', '--strict'], cwd=ROOT, check=True)
    for name in (*MARKETING_PAGES, 'site.css', 'site.js'):
        if name.endswith('.html'):
            (OUT / name).write_text(marketing_links((DOCS / name).read_text()))
        else:
            shutil.copy2(DOCS / name, OUT / name)
    for name in ('assets', 'sales-deck'):
        shutil.copytree(DOCS / name, OUT / name, dirs_exist_ok=True)
    subprocess.run([sys.executable, str(ROOT / 'tools/collect_python_notices.py'),
                    '--output', str(OUT / 'licenses/documentation-build.txt'),
                    'mkdocs', 'mkdocs-material'], cwd=ROOT, check=True)
    for old, record in json.loads((DOCS / 'migration.json').read_text()).items():
        rel = Path(old)
        # Legacy Jekyll/Pages addresses, as well as original raw Markdown links.
        aliases = [rel.with_suffix('.html')]
        if rel.name == 'README.md': aliases += [rel.parent / 'index.html']
        for alias in aliases:
            if alias.as_posix() == 'index.html': continue
            target = OUT / alias
            target.parent.mkdir(parents=True, exist_ok=True)
            def url(mapped):
                p, _, fragment = mapped.partition('#')
                route = page_url(p)
                relative = os.path.relpath(OUT / route, target.parent).replace(os.sep, '/') + '/'
                return relative + ('#' + fragment if fragment else '')
            target.write_text(redirect_document(url(record['target']), {k:url(v) for k,v in record['anchors'].items()}))
        md = OUT / old
        md.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(DOCS / old, md)
    (OUT / '.nojekyll').touch()
    site_url = yaml.safe_load((ROOT / 'mkdocs.yml').read_text())['site_url']
    prefix = urlsplit(site_url).path.rstrip('/').rsplit('/', 1)[0]
    errors = check_links(sorted(OUT.rglob('*.html')), OUT, prefix) + check_migration_output()
    if errors:
        print('\n'.join(errors))
        return False
    print(f'Static site built and checked: {OUT}')
    return True


def public_url(url):
    """Ignore local/private literal addresses and documentation placeholders."""
    parsed = urlsplit(url)
    host = parsed.hostname or ''
    if parsed.scheme not in ('http', 'https') or parsed.username or parsed.password or not host:
        return False
    if '<' in url or '{' in url or host == 'localhost' or host.endswith(('.local', '.localhost', '.internal')):
        return False
    if host in ('example.com', 'example.org', 'example.net') or any(host.endswith('.' + h) for h in ('example.com', 'example.org', 'example.net')):
        return False
    try:
        return ipaddress.ip_address(host).is_global
    except ValueError:
        return '.' in host


def external():
    urls = sorted({u.split('#')[0] for p in source_files() for u in parse(p).links if u.startswith(('https://', 'http://'))})
    # Public, literal URLs only. Never contact local hosts or placeholder destinations.
    urls = [u for u in urls if public_url(u)]
    def probe(url):
        try:
            req = Request(url, headers={'User-Agent':'MagicStick-docs-link-check/1.0'}, method='HEAD')
            with urlopen(req, timeout=10) as response: return {'url':url, 'status':response.status}
        except Exception as exc: return {'url':url, 'warning':str(exc)}
    with ThreadPoolExecutor(max_workers=8) as pool: results = list(pool.map(probe, urls))
    report = ROOT / 'dist/docs-external-links.json'
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(json.dumps(results, indent=2) + '\n')
    print(f'Advisory external links: {sum("warning" in r for r in results)} warnings / {len(results)} URLs. {report}')
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('check', 'build', 'inventory', 'external'))
    args = parser.parse_args()
    if args.command == 'inventory':
        (DOCS / 'reference/compatibility.md').write_text(compatibility())
        return 0
    return 0 if {'check':check, 'build':build, 'external':external}[args.command]() else 1


if __name__ == '__main__':
    raise SystemExit(main())
