class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = []
        self.ids = set()

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        for key in ('id', 'name'):
            if attrs.get(key): self.ids.add(attrs[key])
        if tag == 'a' and attrs.get('href'): self.links.append(attrs['href'])
        if tag in ('img', 'script', 'iframe', 'source') and attrs.get('src'):
            self.links.append(attrs['src'])
        if tag == 'link' and attrs.get('href') and attrs.get('rel') != 'canonical':
            self.links.append(attrs['href'])


def github_headings(text):
    counts, result, fence = {}, set(), None
    for line in text.splitlines():
        f = re.match(r'^\s*(`{3,}|~{3,})', line)
        if f:
            if fence is None: fence = f[1][0]
            elif fence == f[1][0]: fence = None
            continue
        if fence: continue
        match = re.match(r'^#{1,6}\s+(.+?)\s*#*\s*$', line)
        if not match: continue
        label = re.sub(r'<[^>]+>', '', match[1]).lower()
        slug = re.sub(r'[^\w\- ]', '', label).replace(' ', '-')
        n = counts.get(slug, 0)
        counts[slug] = n + 1
        result.add(slug + (f'-{n}' if n else ''))
    return result


def parse(path):
    text = path.read_text(encoding='utf-8')
    parser = Links()
    parser.feed(markdown.markdown(text, extensions=['fenced_code', 'tables']) if path.suffix == '.md' else text)
    if path.suffix == '.md': parser.ids.update(github_headings(text))
    return parser


def local_target(source, href, root, public_prefix=''):
    url = urlsplit(href)
    if url.scheme or url.netloc: return None
    path = unquote(url.path)
    if public_prefix and (path == public_prefix or path.startswith(public_prefix + '/')):
        path = path[len(public_prefix):] or '/'
    target = (root / path.lstrip('/') if path.startswith('/') else source.parent / path) if path else source
    target = Path(os.path.normpath(target))
    if target.is_dir():
        for name in ('index.html', 'README.md', 'index.md'):
            if (target / name).is_file():
                target = target / name
                break
    return target, unquote(url.fragment)


def check_links(paths, root, public_prefix=''):
    errors, cache = [], {}
    def cached(path):
        if path not in cache: cache[path] = parse(path)
        return cache[path]
    for source in paths:
        data = cached(source)
        for href in data.links:
            resolved = local_target(source, href, root, public_prefix)
            if not resolved: continue
            target, fragment = resolved
            if not target.exists():
                errors.append(f'{source.relative_to(root)}: missing target {href}')
            elif fragment and target.suffix in ('.md', '.html'):
                ids = cached(target).ids
                if fragment not in ids:
                    errors.append(f'{source.relative_to(root)}: missing anchor {href}')
    return sorted(set(errors))


def source_files():
    names = subprocess.check_output(['git', 'ls-files', '--cached', '--others', '--exclude-standard', '-z'], cwd=ROOT).decode().split('\0')
    return sorted({ROOT / n for n in names if n and not n.startswith('.codex/')
                   and (ROOT / n).is_file() and (Path(n).suffix == '.md'
                   or (Path(n).suffix == '.html' and n.startswith('docs/')))})


